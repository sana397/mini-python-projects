#!/usr/bin/env python3
import argparse
from pathlib import Path

from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_LEFT
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Preformatted


def parse_markdown_to_flowables(md_text: str):
    styles = getSampleStyleSheet()
    # Base styles
    body = styles['BodyText']
    body.fontName = 'Helvetica'
    body.fontSize = 10
    body.leading = 14

    h1 = styles['Heading1']
    h1.fontName = 'Helvetica-Bold'
    h1.fontSize = 18
    h1.leading = 22
    h1.spaceAfter = 8

    h2 = styles['Heading2']
    h2.fontName = 'Helvetica-Bold'
    h2.fontSize = 14
    h2.leading = 18
    h2.spaceAfter = 6

    h3 = styles['Heading3']
    h3.fontName = 'Helvetica-Bold'
    h3.fontSize = 12
    h3.leading = 16
    h3.spaceAfter = 4

    code_style = ParagraphStyle(
        name='Code',
        fontName='Courier',
        fontSize=9,
        leading=12,
        alignment=TA_LEFT,
    )

    flow = []
    code_mode = False
    code_lines = []

    lines = md_text.splitlines()

    def flush_code():
        nonlocal code_lines
        if code_lines:
            flow.append(Preformatted('\n'.join(code_lines), code_style))
            flow.append(Spacer(1, 6))
            code_lines = []

    for raw in lines:
        line = raw.rstrip('\n')
        if line.strip().startswith('```'):
            if not code_mode:
                code_mode = True
                code_lines = []
            else:
                # closing fence
                code_mode = False
                flush_code()
            continue

        if code_mode:
            code_lines.append(line)
            continue

        # Headings
        if line.startswith('# '):
            flow.append(Paragraph(line[2:].strip(), h1))
            continue
        if line.startswith('## '):
            flow.append(Paragraph(line[3:].strip(), h2))
            continue
        if line.startswith('### '):
            flow.append(Paragraph(line[4:].strip(), h3))
            continue

        # Blank line -> spacer
        if line.strip() == '':
            flow.append(Spacer(1, 6))
            continue

        # Bullet lines (very simple handling)
        if line.lstrip().startswith('- '):
            text = '• ' + line.lstrip()[2:]
            flow.append(Paragraph(text, body))
            continue

        # Default paragraph
        flow.append(Paragraph(line, body))

    # End flush
    if code_mode:
        flush_code()

    return flow


def render_pdf(md_path: Path, out_path: Path):
    md_text = md_path.read_text(encoding='utf-8')
    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54,
        title='Register Transfer Language – Notes',
        author='Generated by Agent Mode',
    )
    flow = parse_markdown_to_flowables(md_text)
    doc.build(flow)


def main():
    ap = argparse.ArgumentParser(description='Render Markdown-like notes (with code blocks) to PDF.')
    ap.add_argument('-i', '--input', required=True, help='Path to input .md file')
    ap.add_argument('-o', '--output', required=True, help='Path to output .pdf file')
    args = ap.parse_args()

    in_path = Path(args.input)
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    render_pdf(in_path, out_path)
    print(f'Wrote PDF: {out_path}')


if __name__ == '__main__':
    main()
